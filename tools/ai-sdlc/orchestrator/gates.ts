// Unit gates. Each returns pass/fail from code, never from a model.
// Order: scope → contracts untouched → produced change → tests changed → checks → red at base → mutation.
import { existsSync, readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { isAbsolute, join } from "node:path";
import { tmpdir } from "node:os";
import picomatch from "picomatch";
import type { Config } from "./config.ts";
import type { Brief, GateResult, Unit } from "./types.ts";
import { changedFiles, git, restoreFrom } from "./git.ts";
import { sh, tail, writeFileEnsured } from "./util.ts";
import { isManifest as isProfileManifest, profileForFile, profilesFor } from "../checks/hooks/profile.mjs";
import { applyMutant, catalogueMutants, changedLinesFromDiff, genericMutants, literalMutants, loadCatalogue, subset, type Mutant } from "../checks/mutation/mutate.ts";

export interface GateContext {
  unit: Unit;
  brief: Brief;
  cwd: string;             // unit worktree
  cfg: Config;
  ledgerPath: string;      // seen-red ledger (shared across units of a ticket)
  workflowRoot: string;
}

const META_FILES = new Set(["owed.yaml"]);

/** Package manifests and lockfiles of any ecosystem: configuration, not implementation (no tests required, never mutated). */
export const isManifest = (p: string) => isProfileManifest(p);

export function matcher(globs: string[]) {
  const ms = globs.map((g) => picomatch(g, { dot: true }));
  return (p: string) => ms.some((m) => m(p));
}

export function isTestFile(p: string, cfg: Config, unitTests: string[]): boolean {
  return matcher([...unitTests, ...cfg.tests.globs])(p);
}

export function scopeGate(files: string[], unit: Unit): GateResult {
  const inScope = matcher(unit.scope);
  const outside = files.filter((f) => !inScope(f) && !META_FILES.has(f));
  return { name: "scope", pass: outside.length === 0, output: outside.length ? `Files changed outside SCOPE (${unit.scope.join(", ")}):\n${outside.map((f) => `  ${f}`).join("\n")}` : "all changes inside SCOPE" };
}

export function contractsGate(files: string[]): GateResult {
  const touched = files.filter((f) => f.startsWith("contracts/"));
  return { name: "contracts-untouched", pass: touched.length === 0, output: touched.length ? `Contracts are generated by the planner; change the IR instead, or add an owed.yaml entry:\n${touched.join("\n")}` : "ok" };
}

export function changeGates(files: string[], unit: Unit, cfg: Config, unitTests: string[]): GateResult[] {
  const work = files.filter((f) => !META_FILES.has(f));
  const tests = work.filter((f) => isTestFile(f, cfg, unitTests));
  const source = work.filter((f) => !isTestFile(f, cfg, unitTests) && !isManifest(f));
  const out: GateResult[] = [];
  const mayNoOp = unit.kind === "foundation" || unit.kind === "wiring";
  if (!work.length && !mayNoOp) out.push({ name: "produced-change", pass: false, output: "The unit produced no change. Every feature unit must add tests and implementation." });
  else out.push({ name: "produced-change", pass: true, output: work.length ? `${work.length} files` : `${unit.kind} already in place (no change)` });
  out.push({
    name: "tests-changed",
    pass: !(source.length && !tests.length),
    output: source.length && !tests.length ? `Implementation changed without any test change:\n${source.join("\n")}` : `${tests.length} test files changed`,
  });
  return out;
}

export function checksGate(cwd: string, commands: string[], name = "checks", env?: Record<string, string>): GateResult {
  const outputs: string[] = [];
  for (const cmd of commands) {
    const r = sh(cmd, { cwd, env: env ? { ...process.env, ...env } : undefined });
    outputs.push(`$ ${cmd} → exit ${r.code}`);
    if (r.code !== 0) return { name, pass: false, output: outputs.join("\n") + "\n" + tail(r.stdout + "\n" + r.stderr, 8000) };
  }
  return { name, pass: true, output: outputs.join("\n") };
}

