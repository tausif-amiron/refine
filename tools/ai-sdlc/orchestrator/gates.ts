// Test reports (vitest/jest JSON reporter)

export interface TestOutcome { file: string; name: string; status: "passed" | "failed" | "skipped" }

/** Parse a test report: JUnit XML (pytest, Go, Java, .NET, ...) or jest/vitest JSON, detected from its content. */
export function parseTestReport(report: string, cwd: string): { tests: TestOutcome[]; failedFiles: string[] } {
  return report.trimStart().startsWith("<") ? parseJunit(report, cwd) : parseJestJson(report, cwd);
}

const XML_ENTITIES: Record<string, string> = { "&lt;": "<", "&gt;": ">", "&amp;": "&", "&quot;": '"', "&apos;": "'" };
const unescapeXml = (s: string) => s.replace(/&(lt|gt|amp|quot|apos);/g, (m) => XML_ENTITIES[m]).replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)));

function xmlAttrs(tag: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const m of tag.matchAll(/([\w:.-]+)\s*=\s*"([^"]*)"/g)) out[m[1]] = unescapeXml(m[2]);
  for (const m of tag.matchAll(/([\w:.-]+)\s*=\s*'([^']*)'/g)) out[m[1]] ??= unescapeXml(m[2]);
  return out;
}

/**
 * JUnit XML. A test case's file comes from its `file` attribute (pytest with junit_family=xunit1, many others),
 * else from a dotted classname ("tests.test_cli.TestX" → tests/test_cli.py when that file exists). A case that
 * errored with no test of its own (a collection or import error) marks its whole file as failed.
 */
export function parseJunit(xml: string, cwd: string): { tests: TestOutcome[]; failedFiles: string[] } {
  const tests: TestOutcome[] = [];
  const failedFiles: string[] = [];
  const rel = (f: string) => f.replace(cwd.endsWith("/") ? cwd : cwd + "/", "");
  // "tests.test_cli.TestX" → the longest prefix that names an existing file (tests/test_cli.py); else as given.
  const fromDotted = (dotted: string) => {
    const parts = dotted.split(".");
    for (let n = parts.length; n > 0; n--) {
      const candidate = parts.slice(0, n).join("/") + ".py";
      if (existsSync(join(cwd, candidate))) return candidate;
    }
    return dotted;
  };
  for (const m of xml.matchAll(/<testcase\b([^>]*?)(\/>|>([\s\S]*?)<\/testcase>)/g)) {
    const a = xmlAttrs(m[1]);
    const body = m[3] ?? "";
    const classname = a.classname ?? "";
    const file = a.file ? rel(a.file) : classname ? fromDotted(classname) : fromDotted(a.name ?? "");
    const errored = /<(failure|error)\b/.test(body);
    if (!classname && errored) { failedFiles.push(file); continue; } // the file itself failed to load
    const status = errored ? "failed" : /<skipped\b/.test(body) ? "skipped" : "passed";
    tests.push({ file, name: classname ? `${classname}.${a.name}` : String(a.name), status });
  }
  return { tests, failedFiles };
}

function parseJestJson(json: string, cwd: string): { tests: TestOutcome[]; failedFiles: string[] } {
  const tests: TestOutcome[] = [];
  const failedFiles: string[] = [];
  let doc: any;
  try { doc = JSON.parse(json); } catch { return { tests, failedFiles }; }
  for (const tr of doc.testResults ?? []) {
    const file = String(tr.name ?? tr.testFilePath ?? "").replace(cwd.endsWith("/") ? cwd : cwd + "/", "");
    const assertions = tr.assertionResults ?? tr.testResults ?? [];
    if (!assertions.length && tr.status === "failed") failedFiles.push(file);
    for (const a of assertions) {
      const status = a.status === "passed" ? "passed" : a.status === "failed" ? "failed" : "skipped";
      tests.push({ file, name: String(a.fullName ?? a.title), status });
    }
  }
  return { tests, failedFiles };
}

export function runTests(cwd: string, cfg: Config, files: string[]): { code: number; tests: TestOutcome[]; failedFiles: string[]; output: string } {
  const dir = mkdtempSync(join(tmpdir(), "ai-sdlc-tests-"));
  const out = join(dir, "report");
  try {
    const cmd = cfg.tests.command.replace("{out}", out).replace("{files}", files.map((f) => `'${f}'`).join(" "));
    const r = sh(cmd, { cwd, timeoutMs: 20 * 60_000 });
    const report = existsSync(out) ? readFileSync(out, "utf8") : r.stdout;
    return { code: r.code, ...parseTestReport(report, cwd), output: r.stdout + r.stderr };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

export const testKey = (t: { file: string; name: string }) => `${t.file}::${t.name}`;

export function loadLedger(path: string): Set<string> {
  return new Set(existsSync(path) ? (JSON.parse(readFileSync(path, "utf8")) as string[]) : []);
}

export function saveLedger(path: string, ledger: Set<string>): void {
  writeFileEnsured(path, JSON.stringify([...ledger].sort(), null, 2) + "\n");
}

/**
 * Red at base: revert the unit's implementation files to the brief's base commit and run the unit's tests.
 * Tests that fail there are added to the seen-red ledger. Returns the tests this unit added (tests that already
 * existed at the base commit are not its to prove).
 */
export interface RedAtBase {
  added: TestOutcome[];
  preexisting: number;
  /** How each test ran without the implementation: passed, failed, or its file did not load. */
  atBase: Map<string, "passed" | "failed" | "skipped" | "not-loaded">;
  implChanged: boolean;
}

export function redAtBase(ctx: GateContext, testFiles: string[], implFiles: string[]): RedAtBase {
  if (!testFiles.length) return { added: [], preexisting: 0, atBase: new Map(), implChanged: implFiles.length > 0 };
  const ledger = loadLedger(ctx.ledgerPath);
  // Tests that already existed at the base commit (in test files that existed then) were written, and seen red,
  // before this unit. Learn which by running the base versions of those files against the base implementation.
  const existed = testFiles.filter((f) => git(ctx.cwd, `cat-file -e '${ctx.brief.base_commit}:${f}'`).code === 0);
  const preexisting = new Set<string>();
  if (existed.length) {
    restoreFrom(ctx.cwd, ctx.brief.base_commit, [...implFiles, ...existed]);
    try {
      for (const t of runTests(ctx.cwd, ctx.cfg, existed).tests) preexisting.add(testKey(t));
    } finally {
      git(ctx.cwd, "checkout HEAD -- .");
      git(ctx.cwd, "clean -fdq -e .ai-sdlc");
    }
  }
  const green = runTests(ctx.cwd, ctx.cfg, testFiles);
  restoreFrom(ctx.cwd, ctx.brief.base_commit, implFiles);
  let base;
  try {
    base = runTests(ctx.cwd, ctx.cfg, testFiles);
  } finally {
    git(ctx.cwd, "checkout HEAD -- .");
    git(ctx.cwd, "clean -fdq -e .ai-sdlc");
  }
  const redFiles = new Set(base.failedFiles);
  for (const t of base.tests) if (t.status === "failed") ledger.add(testKey(t));
  for (const t of green.tests) if (redFiles.has(t.file)) ledger.add(testKey(t));
  saveLedger(ctx.ledgerPath, ledger);
  const atBase: RedAtBase["atBase"] = new Map();
  for (const t of base.tests) atBase.set(testKey(t), t.status);
  for (const t of green.tests) if (redFiles.has(t.file)) atBase.set(testKey(t), "not-loaded");
  return { added: green.tests.filter((t) => t.status !== "skipped" && !preexisting.has(testKey(t))), preexisting: preexisting.size, atBase, implChanged: implFiles.length > 0 };
}

/**
 * Seen red: every test the unit added has failed at least once, without the implementation (red at base) or
 * under a mutant. Tests that pin behaviour which must stay unchanged pass at base by design; a mutant is how they
 * get seen red. Read after the mutation gate has added its kills to the ledger.
 */
/** Is this test a pin (guards behaviour that must stay unchanged)? By its profile's naming convention. */
export function isPin(t: { file: string; name: string }, cfg: Config): boolean {
  const pattern = cfg.tests.pinPattern ?? profileForFile(t.file)?.tests.pinPattern;
  return Boolean(pattern) && new RegExp(pattern!).test(t.name);
}

/**
 * Seen red, and pins. A new test must have failed at least once (without the implementation, or under a mutant).
 * A pin guards behaviour the ticket says must not change, so it is held to the opposite rule: it must pass both
 * without the implementation and with it. A pin that fails without the change is not guarding unchanged behaviour
 * (mislabelled), and a unit that changed its implementation still needs at least one non-pin test seen red.
 */
export function seenRedVerdict(ctx: GateContext, added: TestOutcome[], preexisting: number, atBase?: RedAtBase["atBase"], implChanged = false): GateResult {
  const ledger = loadLedger(ctx.ledgerPath);
  const pins = added.filter((t) => isPin(t, ctx.cfg));
  const regular = added.filter((t) => !isPin(t, ctx.cfg));
  const neverRed = regular.filter((t) => !ledger.has(testKey(t)));
  const badPins = pins.filter((t) => atBase?.get(testKey(t)) !== "passed");
  const onlyPins = implChanged && pins.length > 0 && regular.length === 0;
  const note = preexisting ? ` (${preexisting} tests that already existed at the base commit are not required to be red)` : "";
  const problems: string[] = [];
  if (neverRed.length) {
    // Without this, an agent deletes the test, and the mutation gate then fails on the now-untested line (RT-2).
    const pattern = ctx.cfg.tests.pinPattern ?? profileForFile(neverRed[0].file)?.tests.pinPattern;
    const pinName = pattern?.replace(/^\(\^\|[^)]*\)/, "").replace(/\\/g, "");
    const hint = pinName
      ? `\nIf a test guards behaviour the ticket keeps unchanged (it passes before and after by design), keep it and make it a pin: put "${pinName}" in its name. Pins must pass both without and with the change. Otherwise, make the test fail without your change.`
      : "";
    problems.push(`These tests never failed, neither without the implementation nor under any mutant, so they prove nothing yet (docs/TESTING.md#seen-red)${note}:\n${neverRed.map((t) => `  ${t.file} › ${t.name}`).join("\n")}${hint}`);
  }
  if (badPins.length) problems.push(`These are named as pins but do not pass without the change, so they are not guarding unchanged behaviour. Rename them as ordinary tests, or make them test only what must stay the same:\n${badPins.map((t) => `  ${t.file} › ${t.name} (without the change: ${atBase?.get(testKey(t)) ?? "not run"})`).join("\n")}`);
  if (onlyPins) problems.push("The implementation changed, but every new test is a pin. Add at least one test of the new behaviour that fails without the change.");
  const pinNote = pins.length ? `; ${pins.length} pins pass before and after the change` : "";
  return {
    name: "seen-red",
    pass: problems.length === 0,
    output: problems.length
      ? problems.join("\n\n")
      : added.length ? `${regular.length} new tests, all seen red${pinNote}${note}` : "no unit tests changed",
  };
}

/** Red at base on its own (without mutation): the unit's new tests must all fail without the implementation. */
export function redAtBaseGate(ctx: GateContext, testFiles: string[], implFiles: string[]): GateResult {
  const r = redAtBase(ctx, testFiles, implFiles);
  return seenRedVerdict(ctx, r.added, r.preexisting, r.atBase, r.implChanged);
}

/** Run mutants against the unit's tests. A survivor (all tests still green) fails the gate. */
export function mutationGate(ctx: GateContext, testFiles: string[], implFiles: string[], limit: number | "all"): GateResult & { survivors: Mutant[]; killed: number } {
  if (!testFiles.length || !implFiles.length) return { name: "mutation", pass: true, output: "nothing to mutate: no tests or implementation changed", survivors: [], killed: 0 };
  const diffText = git(ctx.cwd, `diff -U0 ${ctx.brief.base_commit} HEAD -- ${implFiles.map((f) => `'${f}'`).join(" ")}`).stdout;
  const lines = changedLinesFromDiff(diffText);
  const files = implFiles.filter((f) => existsSync(join(ctx.cwd, f))).map((p) => ({ path: p, content: readFileSync(join(ctx.cwd, p), "utf8") }));
  // First tier on the changed lines; when none applies (declarative code), the literal tier instead.
  const generic = files.flatMap((f) => genericMutants(f.path, f.content, lines.get(f.path) ?? []));
  const literal = generic.length ? [] : files.flatMap((f) => literalMutants(f.path, f.content, lines.get(f.path) ?? []));
  const tierNote = literal.length ? " (literal mutants: the change has no comparisons, logic or arithmetic to mutate)" : "";
  let mutants = [
    ...generic,
    ...literal,
    ...catalogueMutants(loadCatalogue(isAbsolute(ctx.cfg.mutation.catalogue) ? ctx.cfg.mutation.catalogue : join(ctx.cwd, ctx.cfg.mutation.catalogue)), files),
  ];
  mutants = limit === "all" ? subset(mutants, mutants.length) : subset(mutants, limit);
  const ledger = loadLedger(ctx.ledgerPath);
  const survivors: Mutant[] = [];
  let killed = 0;
  for (const m of mutants) {
    const path = join(ctx.cwd, m.file);
    const original = readFileSync(path, "utf8");
    writeFileSync(path, applyMutant(original, m));
    try {
      const r = runTests(ctx.cwd, ctx.cfg, testFiles);
      const red = r.tests.filter((t) => t.status === "failed");
      red.forEach((t) => ledger.add(testKey(t)));
      if (r.code !== 0 || red.length || r.failedFiles.length) killed++;
      else survivors.push(m);
    } finally {
      writeFileSync(path, original);
    }
  }
  saveLedger(ctx.ledgerPath, ledger);
  return {
    name: "mutation",
    pass: survivors.length === 0,
    survivors, killed,
    output: survivors.length
      ? `${survivors.length} of ${mutants.length} mutants survived (no test went red). Add tests that fail for these changes, or mark an equivalent line with "ai-sdlc-mutation: skip":\n${survivors.map((m) => `  ${m.file}:${m.line} [${m.operator}]\n    - ${m.original.trim()}\n    + ${m.mutated.trim()}`).join("\n")}`
      : mutants.length ? `${killed} of ${mutants.length} mutants killed${tierNote}` : "no applicable mutants: this change is not tested by mutation",
  };
}

export interface LintFinding { ruleId: string; message: string; line: number }

/** Lint one file's content through an ESLint-compatible command (--stdin, JSON). Errors only. */
type LintSpec = { stdinArgs?: string; format?: string };

/** Lint one file's content through the profile's linter (stdin, JSON). Errors only. */
export function lintFindings(cmd: string, cwd: string, file: string, content: string, spec: LintSpec = { stdinArgs: "--format json --stdin --stdin-filename '{file}'", format: "eslint-json" }): LintFinding[] | { error: string } {
  const args = (spec.stdinArgs ?? "").replaceAll("{file}", file.replace(/'/g, ""));
  const r = sh(`${cmd} ${args}`, { cwd, input: content });
  try {
    const out = JSON.parse(r.stdout);
    if (spec.format === "ruff-json") {
      // [{ code, message, location: { row } }]; ruff reports only what it is configured to fail on.
      return (out as { code?: string | null; message: string; location?: { row?: number } }[]).map((m) => ({ ruleId: m.code ?? "syntax", message: m.message, line: m.location?.row ?? 0 }));
    }
    const results = out as { messages?: { ruleId?: string | null; message: string; severity: number; line?: number }[] }[];
    return (results[0]?.messages ?? []).filter((m) => m.severity === 2).map((m) => ({ ruleId: m.ruleId ?? "parse", message: m.message, line: m.line ?? 0 }));
  } catch {
    return { error: tail(r.stdout + r.stderr, 2000) || `exit ${r.code}` };
  }
}


/**
 * Lint gate for repos whose code already has lint errors: a unit fails only on errors it added. Each changed
 * file is linted as it is now and as it was at the brief's base commit; an error counts as new when its rule
 * and message occur more often now than before (line numbers are ignored, since edits move them).
 */
export function lintNewGate(ctx: GateContext, files: string[]): GateResult {
  const cmd = ctx.cfg.checks.lintChanged;
  if (!cmd) return { name: "lint-new", pass: true, output: "not configured" };
  // Lint only files of the active profile that has a linter (the lint command is for the repo's own stack).
  const active = profilesFor(ctx.cwd, ctx.cfg).filter((p) => p.lint);
  const spec = active[0]?.lint;
  const targets = files.filter((f) => profileForFile(f, active.slice(0, 1)) && existsSync(join(ctx.cwd, f)));
  const added: string[] = [];
  for (const f of targets) {
    const now = lintFindings(cmd, ctx.cwd, f, readFileSync(join(ctx.cwd, f), "utf8"), spec);
    if ("error" in now) {
      // If the linter cannot lint even an empty file, the command is broken: a setup problem, not the agent's code.
      const probe = lintFindings(cmd, ctx.cwd, f, "", spec);
      if ("error" in probe) return { name: "lint-new", pass: false, setup: true, output: `Setup problem: the lint command (checks.lintChanged: ${cmd}) cannot run, even on an empty file. Fix the configuration; the unit's code is not at fault.\n${now.error}` };
      return { name: "lint-new", pass: false, output: `Lint could not run on ${f}:\n${now.error}` };
    }
    const before = git(ctx.cwd, `show ${ctx.brief.base_commit}:'${f}'`);
    const prev = before.code === 0 ? lintFindings(cmd, ctx.cwd, f, before.stdout, spec) : [];
    const counts = new Map<string, number>();
    for (const p of "error" in prev ? [] : prev) counts.set(`${p.ruleId}|${p.message}`, (counts.get(`${p.ruleId}|${p.message}`) ?? 0) + 1);
    for (const n of now) {
      const k = `${n.ruleId}|${n.message}`;
      const c = counts.get(k) ?? 0;
      if (c > 0) counts.set(k, c - 1);
      else added.push(`  ${f}:${n.line} ${n.ruleId}: ${n.message}`);
    }
  }
  return {
    name: "lint-new",
    pass: added.length === 0,
    output: added.length ? `${added.length} new lint error(s) in files this unit changed (errors that were already there do not count):\n${added.join("\n")}` : `${targets.length} changed file(s), no new lint errors`,
  };
}

/**
 * The repo's own mutation tool (config mutation.external): when a unit adds entries to the repo's mutation
 * catalogue, run the tool on exactly those entries. Each must be caught (the command exits 0).
 */
export function externalMutationGate(ctx: GateContext): GateResult | undefined {
  const ext = ctx.cfg.mutation.external;
  if (!ext) return undefined;
  const added = git(ctx.cwd, `diff -U0 ${ctx.brief.base_commit} HEAD -- '${ext.catalogue}'`).stdout
    .split("\n").filter((l) => l.startsWith("+") && !l.startsWith("+++")).map((l) => l.slice(1));
  const idRe = new RegExp(ext.idPattern);
  const ids = added.map((l) => l.match(idRe)?.[1]).filter((x): x is string => Boolean(x));
  if (!ids.length) return { name: "mutation-external", pass: true, output: `no new entries in ${ext.catalogue}` };
  const failed: string[] = [];
  for (const id of ids) {
    const cmd = ext.command.replaceAll("{id}", id);
    const r = sh(cmd, { cwd: ctx.cwd, timeoutMs: 30 * 60_000 });
    if (r.code !== 0) failed.push(`$ ${cmd} → exit ${r.code}\n${tail(r.stdout + r.stderr, 3000)}`);
  }
  return {
    name: "mutation-external",
    pass: failed.length === 0,
    output: failed.length
      ? `${failed.length} of ${ids.length} new ${ext.catalogue} entries not caught by the repo's own mutation tool:\n${failed.join("\n\n")}`
      : `${ids.length} new catalogue mutation(s) caught by the repo's tool: ${ids.join(", ")}`,
  };
}

/** All unit gates in order. Stops at the first failing group so the fix brief stays focused. */
export function runUnitGates(ctx: GateContext): GateResult[] {
  const files = changedFiles(ctx.cwd, ctx.brief.base_commit);
  const results: GateResult[] = [scopeGate(files, ctx.unit), contractsGate(files), ...changeGates(files, ctx.unit, ctx.cfg, ctx.brief.tests)];
  if (results.some((r) => !r.pass)) return results;
  const checks = checksGate(ctx.cwd, ctx.cfg.checks.full);
  results.push(checks);
  if (!checks.pass) return results;
  if (ctx.cfg.checks.lintChanged) {
    const lint = lintNewGate(ctx, files.filter((f) => !META_FILES.has(f) && !isManifest(f)));
    results.push(lint);
    if (!lint.pass) return results;
  }
  const testFiles = files.filter((f) => isTestFile(f, ctx.cfg, ctx.brief.tests) && existsSync(join(ctx.cwd, f)));
  const implFiles = files.filter((f) => !isTestFile(f, ctx.cfg, ctx.brief.tests) && !META_FILES.has(f) && !isManifest(f));
  // Seen red is decided after mutation: a test that pins unchanged behaviour passes at base, and is seen red when
  // a mutant breaks that behaviour.
  const red = redAtBase(ctx, testFiles, implFiles);
  const mut = mutationGate(ctx, testFiles, implFiles, ctx.cfg.mutation.fastSubset);
  results.push(seenRedVerdict(ctx, red.added, red.preexisting, red.atBase, red.implChanged));
  results.push({ name: mut.name, pass: mut.pass, output: mut.output });
  const ext = externalMutationGate(ctx);
  if (ext) results.push(ext);
  return results;
}

export function gateReport(results: GateResult[]): string {
  return results.map((r) => `[${r.pass ? "PASS" : "FAIL"}] ${r.name}\n${r.output}`).join("\n\n");
}
